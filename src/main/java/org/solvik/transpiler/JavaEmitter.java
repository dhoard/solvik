    private SolvikProgram lowerProgram() {
        List<SolvikProgram.Trait> traits = new ArrayList<>();
        List<SolvikProgram.Enum> enums = new ArrayList<>();
        List<SolvikProgram.Struct> structs = new ArrayList<>();
        for (Decl declaration : model.unit.declarations()) {
            if (declaration instanceof TraitDecl i) traits.add(lowerTrait(i));
            else if (declaration instanceof EnumDecl e) enums.add(lowerEnum(e));
        }
        int structIndex = 0;
        for (Decl declaration : model.unit.declarations()) if (declaration instanceof StructDecl s) structs.add(lowerStruct(s, structIndex++));
        return new SolvikProgram(traits, enums, structs);
    }

    private List<SolvikProgram.TypeParameter> lowerTypeParameters(List<TypeParam> params) {
        if (params.isEmpty()) return List.of();
        List<SolvikProgram.TypeParameter> result = new ArrayList<>(params.size());
        for (TypeParam p : params) result.add(new SolvikProgram.TypeParameter(p.name(), lowerTypeRefs(p.constraints())));
        return result;
    }

    /**
     * Lower a list of type references with a plain loop. Type-reference lists
     * are small and are consulted for every declaration, so avoiding a stream
     * (and an empty-list allocation) keeps lowering allocation-free for the
     * common no-argument case such as {@code Long} or {@code Self}.
     */
    private List<Type> lowerTypeRefs(List<TypeRef> refs) {
        if (refs.isEmpty()) return List.of();
        List<Type> result = new ArrayList<>(refs.size());
        for (TypeRef ref : refs) result.add(typeOf(ref));
        return result;
    }

    private SolvikProgram.Trait lowerTrait(TraitDecl declaration) {
        owner = declaration.name();
        List<SolvikProgram.Method> methods = new ArrayList<>();
        for (MethodDecl method : declaration.methods()) methods.add(lowerMethod(method));
        return new SolvikProgram.Trait(declaration.name(), lowerTypeParameters(declaration.typeParams()), lowerTypeRefs(declaration.extendsTypes()), methods);
    }

    private SolvikProgram.Enum lowerEnum(EnumDecl declaration) {
        owner = declaration.name();
        List<SolvikProgram.Variant> variants = new ArrayList<>();
        for (VariantDecl v : declaration.variants()) variants.add(new SolvikProgram.Variant(v.name(), v.payload() == null ? null : typeOf(v.payload())));
        return new SolvikProgram.Enum(declaration.name(), lowerTypeParameters(declaration.typeParams()), variants);
    }

    private SolvikProgram.Struct lowerStruct(StructDecl declaration, int index) {
        owner = declaration.name();
        List<SolvikProgram.Field> fields = new ArrayList<>();
        for (FieldDecl field : declaration.fields()) { Type type = typeOf(field.type()); fields.add(new SolvikProgram.Field(field.name(), type, field.isVar(), field.isStatic(), field.initializer() == null ? null : lower(field.initializer(), type))); }
        List<SolvikProgram.Method> methods = new ArrayList<>();
        for (MethodDecl method : declaration.methods()) methods.add(lowerMethod(method));
        methods.addAll(lowerDelegates(declaration));
        List<SolvikStmt> staticBlock = declaration.staticBlock() == null ? null : lowerBlock(declaration.staticBlock());
        return new SolvikProgram.Struct(declaration.name(), lowerTypeParameters(declaration.typeParams()), fields, methods, staticBlock, lowerTypeRefs(declaration.implementsTypes()), index);
    }

    private SolvikProgram.Method lowerMethod(MethodDecl method) {
        currentMethod = method;
        List<SolvikProgram.Parameter> params = new ArrayList<>();
        for (Param p : method.params()) params.add(new SolvikProgram.Parameter(p.name(), typeOf(p.type()), p.variadic(), methodParameterNeedsReferenceSignature(method, p)));
        List<SolvikStmt> body = null;
        if (method.body() != null) { body = lowerAccumulatorRecursion(method); if (body == null) body = lowerBlock(method.body()); }
        return new SolvikProgram.Method(method.name(), params, typeOf(method.returnType()), methodNeedsReferenceSignature(method), method.isPub(), method.instance(), lowerTypeParameters(methodTypeParametersList(method)), body);
    }

    private List<TypeParam> methodTypeParametersList(MethodDecl method) {
        List<TypeParam> parameters = new ArrayList<>();
        if (!method.instance() && owner != null && model.structs.containsKey(owner)) parameters.addAll(model.structs.get(owner).declaration.typeParams());
        for (TypeParam p : method.typeParams()) if (parameters.stream().noneMatch(x -> x.name().equals(p.name()))) parameters.add(p);
        return parameters;
    }

    /** Lower the common linear accumulator recursion without consuming the Java stack. */
    private List<SolvikStmt> lowerAccumulatorRecursion(MethodDecl method) {
        if (method.instance() || method.params().size() != 1 || method.typeParams().size() != 0 || method.body().statements().size() != 2) return null;
        if (!(method.body().statements().get(0) instanceof IfStmt branch) || !(method.body().statements().get(1) instanceof ReturnStmt result)) return null;
        if (!(branch.condition() instanceof BinaryExpr condition) || condition.op() != BinaryOp.EQ || !(condition.left() instanceof NameExpr variable) || !(condition.right() instanceof Literal zero) || zero.kind() != LiteralKind.INT || !SemanticAnalyzer.cleanInteger(zero.text()).equals("0")) return null;
        if (branch.thenBlock().statements().size() != 1 || !(branch.thenBlock().statements().get(0) instanceof ReturnStmt base) || !(base.value() instanceof Literal baseValue)) return null;
        if (!(result.value() instanceof BinaryExpr sum) || sum.op() != BinaryOp.ADD) return null;
        Expr term = null; CallExpr recursive = null;
        if (sum.left() instanceof CallExpr c) { recursive = c; term = sum.right(); } else if (sum.right() instanceof CallExpr c) { recursive = c; term = sum.left(); }
        if (recursive == null || !(recursive.callee() instanceof StaticExpr target) || !target.name().equals(method.name()) || recursive.arguments().size() != 1) return null;
        if (!(recursive.arguments().get(0).expression() instanceof BinaryExpr decrement) || decrement.op() != BinaryOp.SUB || !(decrement.left() instanceof NameExpr n) || !n.name().equals(variable.name()) || !(decrement.right() instanceof Literal one) || one.kind() != LiteralKind.INT || !SemanticAnalyzer.cleanInteger(one.text()).equals("1")) return null;
        if (!method.returnType().name().equals("Long") || method.returnType().nullable() || !method.params().get(0).type().name().equals("Long") || method.params().get(0).type().nullable()) return null;
        Type longType = named(Base.LONG, "Long"); Type boolType = named(Base.BOOLEAN, "Boolean");
        localRenames.put(variable.name(), "__value");
        SolvikIr termIr = lower(term, longType);
        localRenames.remove(variable.name());
        List<SolvikStmt> body = new ArrayList<>();
        body.add(new SolvikStmt.VarDecl("__acc", longType, new SolvikIr.Literal(LiteralKind.INT, SemanticAnalyzer.cleanInteger(baseValue.text()), longType)));
        body.add(new SolvikStmt.VarDecl("__value", longType, new SolvikIr.Local(variable.name(), longType)));
        SolvikIr loopCondition = new SolvikIr.Unary(UnaryOp.NOT, new SolvikIr.Binary(BinaryOp.EQ, new SolvikIr.Local("__value", longType), new SolvikIr.Literal(LiteralKind.INT, "0", longType), longType, longType, boolType), boolType, boolType);
        List<SolvikStmt> loopBody = new ArrayList<>();
        loopBody.add(new SolvikStmt.Expr(new SolvikIr.Update(BinaryOp.ADD, new SolvikIr.Local("__acc", longType), termIr, longType, longType, longType)));
        loopBody.add(new SolvikStmt.Expr(new SolvikIr.Update(BinaryOp.SUB, new SolvikIr.Local("__value", longType), new SolvikIr.Literal(LiteralKind.INT, "1", longType), longType, longType, longType)));
        body.add(new SolvikStmt.While(loopCondition, loopBody));
        body.add(new SolvikStmt.Return(new SolvikIr.Local("__acc", longType)));
        return body;
    }

    private List<SolvikProgram.Method> lowerDelegates(StructDecl declaration) {
        List<SolvikProgram.Method> result = new ArrayList<>(); Set<String> emitted = new java.util.HashSet<>();
        for (DelegateDecl delegate : declaration.delegates()) {
            TraitDecl iface = model.traits.get(delegate.traitType().name()).declaration;
            Type ifaceType = typeOf(delegate.traitType());
            for (MethodDecl method : traitMethods(iface)) if (emitted.add(method.name()) && declaration.methods().stream().noneMatch(x -> x.name().equals(method.name()))) {
                currentMethod = method;
                List<SolvikProgram.Parameter> params = new ArrayList<>();
                List<SolvikIr> args = new ArrayList<>();
                for (Param p : method.params()) { Type parameter = delegateTypeOf(p.type(), ifaceType); params.add(new SolvikProgram.Parameter(p.name(), parameter, p.variadic(), traitTypeVariable(p.type(), iface))); args.add(new SolvikIr.Local(p.name(), parameter)); }
                Type returnType = delegateTypeOf(method.returnType(), ifaceType);
                SolvikIr.Call call = new SolvikIr.Call(new SolvikIr.Field(owner, delegate.field(), false, ifaceType), null, false, null, false, method.name(), null, args, ifaceType, returnType);
                List<SolvikStmt> body = new ArrayList<>();
                if (returnType.base() == Base.VOID) body.add(new SolvikStmt.Expr(call)); else body.add(new SolvikStmt.Return(call));
                result.add(new SolvikProgram.Method(method.name(), params, returnType, traitTypeVariable(method.returnType(), iface), true, true, lowerTypeParameters(methodTypeParametersList(method)), body));
            }
        }
        return result;
    }

    private List<MethodDecl> traitMethods(TraitDecl iface) {
        List<MethodDecl> cached = traitMethodCache.get(iface.name());
        if (cached != null) return cached;
        List<MethodDecl> result = new ArrayList<>(iface.methods());
        for (TypeRef parent : iface.extendsTypes()) {
            TraitDecl inherited = model.traits.containsKey(parent.name()) ? model.traits.get(parent.name()).declaration : null;
            if (inherited != null) for (MethodDecl method : traitMethods(inherited)) if (result.stream().noneMatch(x -> x.name().equals(method.name()))) result.add(method);
        }
        List<MethodDecl> immutable = List.copyOf(result);
        traitMethodCache.put(iface.name(), immutable);
        return immutable;
    }

    private boolean methodNeedsReferenceSignature(MethodDecl method) {
        if (owner == null || !model.structs.containsKey(owner) || !method.instance()) return false;
        StructDecl declaration = model.structs.get(owner).declaration;
        for (TypeRef implemented : declaration.implementsTypes()) {
            Type ifaceType = typeOf(implemented);
            if (!model.traits.containsKey(ifaceType.name())) continue;
            TraitDecl iface = model.traits.get(ifaceType.name()).declaration;
            for (MethodDecl candidate : traitMethods(iface)) {
                if (candidate.name().equals(method.name()) && candidate.params().size() == method.params().size()) {
                    if (traitTypeVariable(candidate.returnType(), iface)) return true;
                    for (int i = 0; i < candidate.params().size(); i++) if (traitTypeVariable(candidate.params().get(i).type(), iface)) return true;
                }
            }
        }
        return false;
    }

    private boolean methodParameterNeedsReferenceSignature(MethodDecl method, Param parameter) {
        if (owner == null || !model.structs.containsKey(owner) || !method.instance()) return false;
        StructDecl declaration = model.structs.get(owner).declaration;
        for (TypeRef implemented : declaration.implementsTypes()) {
            Type ifaceType = typeOf(implemented);
            if (!model.traits.containsKey(ifaceType.name())) continue;
            TraitDecl iface = model.traits.get(ifaceType.name()).declaration;
            for (MethodDecl candidate : traitMethods(iface)) {
                if (!candidate.name().equals(method.name()) || candidate.params().size() != method.params().size()) continue;
                for (int i = 0; i < candidate.params().size(); i++) if (candidate.params().get(i).name().equals(parameter.name())) return traitTypeVariable(candidate.params().get(i).type(), iface);
            }
        }
        return false;
    }

    private boolean traitTypeVariable(TypeRef ref, TraitDecl iface) {
        if (ref == null) return false;
        if (iface.typeParams().stream().anyMatch(p -> p.name().equals(ref.name()))) return true;
        return ref.args().stream().anyMatch(arg -> traitTypeVariable(arg, iface));
    }

    private Type delegateTypeOf(TypeRef ref, Type ifaceType) {
        if (ref == null) return named(Base.VOID, "Void");
        List<TypeParam> params = model.traits.containsKey(ifaceType.name()) ? model.traits.get(ifaceType.name()).declaration.typeParams() : List.of();
        for (int i = 0; i < params.size() && i < ifaceType.args().size(); i++) if (params.get(i).name().equals(ref.name())) return ifaceType.args().get(i);
        if (currentMethod != null && currentMethod.typeParams().stream().anyMatch(p -> p.name().equals(ref.name()))) return var(ref.name());
        if (ref.name().equals("Self")) return new Type(Base.STRUCT, owner, model.structs.get(owner).declaration.typeParams().stream().map(p -> var(p.name())).toList(), ref.nullable());
        List<Type> args = ref.args().stream().map(x -> delegateTypeOf(x, ifaceType)).toList();
        Type t = fromName(ref.name(), args, ref.nullable());
        if (t.base() == Base.UNKNOWN) { if (model.structs.containsKey(ref.name())) t = new Type(Base.STRUCT, ref.name(), args, ref.nullable()); else if (model.traits.containsKey(ref.name())) t = new Type(Base.TRAIT, ref.name(), args, ref.nullable()); else if (model.enums.containsKey(ref.name())) t = new Type(Base.ENUM, ref.name(), args, ref.nullable()); }
        return t;
    }

    private void emitTrait(SolvikProgram.Trait declaration) {
        line("public interface " + traitNames.get(declaration.name()) + typeParametersIr(declaration.typeParameters()) + extendsTraitsIr(declaration.extendsTypes()) + " {"); indent();
        for (SolvikProgram.Method method : declaration.methods()) {
            line("@SuppressWarnings(\"finally\")");
            String signature = "public " + (method.body() == null ? "" : "default ") + methodTypeParametersIr(method) + javaType(method.returnType(), method.returnBoxed()) + " " + methodName(method.name()) + "(" + parametersIr(method.params()) + ")";
            if (method.body() == null) line(signature + ";");
            else { line(signature + " {"); indent(); for (SolvikStmt s : method.body()) emitStmt(s); outdent(); line("}"); }
        }
        outdent(); line("}");
    }

    private String extendsTraitsIr(List<Type> refs) {
        if (refs.isEmpty()) return "";
        StringBuilder s = new StringBuilder(" extends ");
        for (int i = 0; i < refs.size(); i++) { if (i > 0) s.append(", "); s.append(javaType(refs.get(i))); }
        return s.toString();
    }

    private void emitEnum(SolvikProgram.Enum declaration) {
        String n = enumNames.get(declaration.name());
        line("public static final class " + n + typeParametersIr(declaration.typeParameters()) + " {"); indent();
        line("private final int tag; private final Object payload;");
        line("private " + n + "(int tag,Object payload){this.tag=tag;this.payload=payload;}");
        for (int i = 0; i < declaration.variants().size(); i++) {
            SolvikProgram.Variant v = declaration.variants().get(i);
            if (v.payload() == null) line("@SuppressWarnings(\"rawtypes\") public static final " + n + " " + v.name() + " = new " + n + "(" + i + ", null);");
            else line("public static " + (declaration.typeParameters().isEmpty() ? "" : typeParametersIr(declaration.typeParameters()) + " ") + n + typeArgumentsIr(declaration.typeParameters()) + " " + v.name() + "(" + javaType(v.payload()) + " value){return new " + n + typeArgumentsIr(declaration.typeParameters()) + "(" + i + ",value);}");
        }
        line("int tag(){return tag;} Object payload(){return payload;}");
        line("@Override public boolean equals(Object o){return o instanceof " + n + (declaration.typeParameters().isEmpty() ? "" : "<?>") + " x && tag==x.tag && RT.eq(payload,x.payload);}");
        line("@Override public int hashCode(){return 31*tag+Objects.hashCode(payload);}");
        line("@Override public String toString(){return payload==null?Integer.toString(tag):Integer.toString(tag)+\"(\"+RT.format(payload)+\")\";}");
        outdent(); line("}");
    }

    private void emitStruct(SolvikProgram.Struct declaration) {
        StringBuilder header = new StringBuilder("public static final class ").append(structNames.get(declaration.name())).append(typeParametersIr(declaration.typeParameters()));
        List<String> bases = new ArrayList<>();
        for (Type t : declaration.implementsTypes()) { if (t.base() == Base.RUNNABLE) bases.add("RT.RunnableLike"); else bases.add(javaType(t)); }
        if (!bases.isEmpty()) header.append(" implements ").append(String.join(", ", bases));
        line(header + " {"); indent();
        for (SolvikProgram.Field field : declaration.fields()) {
            String modifier = field.isStatic() ? "private static " : field.isVar() ? "private " : "private final ";
            line(modifier + javaType(field.type()) + " " + fieldName(field.name()) + (field.initializer() == null ? ";" : " = " + emitIr(field.initializer()) + ";"));
        }
        List<SolvikProgram.Field> instanceFields = new ArrayList<>();
        for (SolvikProgram.Field f : declaration.fields()) if (!f.isStatic()) instanceFields.add(f);
        StringBuilder constructorParameters = new StringBuilder();
        for (int i = 0; i < instanceFields.size(); i++) { if (i > 0) constructorParameters.append(", "); SolvikProgram.Field f = instanceFields.get(i); constructorParameters.append(javaType(f.type())).append(' ').append(fieldName(f.name())); }
        line("private " + structNames.get(declaration.name()) + "(" + constructorParameters + ") {"); indent();
        for (SolvikProgram.Field f : instanceFields) line("this." + fieldName(f.name()) + " = " + fieldName(f.name()) + ";");
        outdent(); line("}");
        line(String.format("@Override public String toString(){return \"<instance #%d>\";}", declaration.index()));
        if (declaration.staticBlock() != null) { line("static {"); indent(); boolean previous = emittingStaticBlock; emittingStaticBlock = true; for (SolvikStmt s : declaration.staticBlock()) emitStmt(s); emittingStaticBlock = previous; outdent(); line("}"); }
        for (SolvikProgram.Method method : declaration.methods()) {
            // A trivial `new` factory (a pure field permutation of its parameters) has
            // every call site lowered straight to the generated all-fields constructor,
            // so the synthetic `__new` forwarding method would be dead code; omit it.
            if (isTrivialFactory(declaration.name(), method)) continue;
            emitMethod(method);
        }
        outdent(); line("}");
    }

    /** True for the synthetic `new` factory of a struct whose construction lowers directly to the constructor. */
    private boolean isTrivialFactory(String structName, SolvikProgram.Method method) {
        return method.name().equals("new") && !method.instance() && trivialFactories.containsKey(structName);
    }

    private void emitMethod(SolvikProgram.Method method) {
        String access = method.isPub() ? "public " : "private ";
        if (!method.instance()) access += "static ";
        line("@SuppressWarnings(\"finally\")");
        line(access + methodTypeParametersIr(method) + javaType(method.returnType(), method.returnBoxed()) + " " + methodName(method.name()) + "(" + parametersIr(method.params()) + ") {"); indent();
        if (method.body() != null) for (SolvikStmt s : method.body()) emitStmt(s);
        outdent(); line("}");
    }

    private String typeParametersIr(List<SolvikProgram.TypeParameter> params) {
        if (params.isEmpty()) return "";
        return "<" + params.stream().map(p -> {
            String bounds = p.bounds().stream().map(this::javaType).reduce((a,b)->a+" & "+b).orElse("");
            return p.name() + (bounds.isEmpty() ? "" : " extends " + bounds);
        }).reduce((a,b)->a+", "+b).orElse("") + ">";
    }

    private String methodTypeParametersIr(SolvikProgram.Method method) {
        return method.typeParameters().isEmpty() ? "" : typeParametersIr(method.typeParameters()) + " ";
    }

    private String typeArgumentsIr(List<SolvikProgram.TypeParameter> params) { return params.isEmpty() ? "" : "<" + params.stream().map(SolvikProgram.TypeParameter::name).reduce((a,b)->a+", "+b).orElse("") + ">"; }

    private String parametersIr(List<SolvikProgram.Parameter> params) {
        if (params.isEmpty()) return "";
        StringBuilder result = new StringBuilder();
        for (int i = 0; i < params.size(); i++) {
            if (i > 0) result.append(", ");
            SolvikProgram.Parameter p = params.get(i);
            result.append(p.variadic() ? "RT.SList<" + javaType(p.type(), true) + ">" : javaType(p.type(), p.boxed())).append(' ').append(localName(p.name()));
        }
        return result.toString();
    }

    private String typeArgumentsOf(List<TypeParam> params) { return params.isEmpty() ? "" : "<" + params.stream().map(TypeParam::name).reduce((a,b)->a+", "+b).orElse("") + ">"; }
    private String fieldName(String n) { return "f_" + n; }
    private String localName(String n) { return n.startsWith("__") ? n : "v_" + n; }

    private void emitMain() {
        line("public static void main(String[] args) {"); indent();
        line("try {"); indent();
        line("int __exit = " + structNames.get("Main") + ".run(RT.strings(args));");
        line("System.exit(__exit);");
        outdent(); line("} catch (RT.Thrown __t) {"); indent();
        line("System.err.println(\"runtime error: \" + RT.format(__t.value));"); line("System.exit(2);");
        outdent(); line("} catch (ExceptionInInitializerError __t) {"); indent();
        line("Throwable __cause = __t.getCause(); if (__cause instanceof RT.Thrown __rt) System.err.println(\"runtime error: \" + RT.format(__rt.value)); else System.err.println(\"runtime error: \" + (__cause == null ? __t.toString() : __cause.getMessage()));"); line("System.exit(2);");
        outdent(); line("} catch (RuntimeException __t) {"); indent();
        line("System.err.println(\"runtime error: \" + __t.getMessage());"); line("System.exit(2);");
        outdent(); line("}"); outdent(); line("}");
    }

    private void emitBlockContents(Block block) { for (Stmt statement : block.statements()) emitStmt(lowerStmt(statement)); }
    private List<SolvikStmt> lowerBlock(Block block) { List<SolvikStmt> result = new ArrayList<>(); for (Stmt statement : block.statements()) result.add(lowerStmt(statement)); return result; }

    private SolvikStmt lowerStmt(Stmt statement) {
        if (statement instanceof VarDecl d) { Type declared = typeOf(d.type()); return new SolvikStmt.VarDecl(d.name(), declared, d.initializer() == null ? null : lowerValue(d.initializer(), declared)); }
        if (statement instanceof ExprStmt e) { if (e.expression() instanceof MatchExpr m) { Type subjectType = model.type(m.subject()); List<SolvikIr.MatchArm> arms = new ArrayList<>(); for (MatchArm arm : m.arms()) arms.add(new SolvikIr.MatchArm(lowerPattern(arm.pattern(), subjectType), lower(arm.body(), null))); return new SolvikStmt.MatchStmt(lower(m.subject(), null), arms); } return new SolvikStmt.Expr(lower(e.expression(), null)); }
        if (statement instanceof ReturnStmt r) { Type declared = typeOf(currentMethod.returnType()); return new SolvikStmt.Return(r.value() == null ? null : lowerValue(r.value(), declared)); }
        if (statement instanceof IfStmt i) { List<SolvikStmt> thenBranch = lowerBlock(i.thenBlock()); List<SolvikStmt> elseBranch = new ArrayList<>(); if (i.elseBranch() != null) { if (i.elseBranch() instanceof BlockStmt b) elseBranch = lowerBlock(b.block()); else elseBranch.add(lowerStmt(i.elseBranch())); } return new SolvikStmt.If(lower(i.condition(), named(Base.BOOLEAN, "Boolean")), thenBranch, elseBranch); }
        if (statement instanceof WhileStmt w) return new SolvikStmt.While(lower(w.condition(), named(Base.BOOLEAN, "Boolean")), lowerBlock(w.body()));
        if (statement instanceof ForStmt f) {
            Type iterable = model.type(f.iterable());
            if (f.iterable() instanceof BinaryExpr b && b.op() == BinaryOp.CONCAT && model.type(b.left()).integral() && model.type(b.right()).integral()) {
                Type loopType = binaryPromotion(model.type(b.left()), model.type(b.right()));
                return new SolvikStmt.ForRange(f.name(), loopType, lower(b.left(), loopType), lower(b.right(), loopType), false, lowerBlock(f.body()));
            }
            return new SolvikStmt.ForEach(f.name(), iterableElement(iterable), lower(f.iterable(), iterable), lowerBlock(f.body()));
        }
        if (statement instanceof SwitchStmt s) { Type subjectType = model.type(s.subject()); List<SolvikStmt.SwitchCase> cases = new ArrayList<>(); for (SwitchCase c : s.cases()) { List<SolvikIr> values = new ArrayList<>(); for (Expr v : c.values()) values.add(lower(v, subjectType)); cases.add(new SolvikStmt.SwitchCase(c.isDefault(), values, lowerBlock(c.body()))); } return new SolvikStmt.Switch(lower(s.subject(), subjectType), subjectType, directEqualityType(subjectType), cases); }
        if (statement instanceof TryStmt t) { List<SolvikStmt.Catch> catches = new ArrayList<>(); for (CatchClause c : t.catches()) catches.add(new SolvikStmt.Catch(typeOf(c.type()), c.name(), lowerBlock(c.body()))); return new SolvikStmt.Try(lowerBlock(t.body()), catches, t.finallyBlock() == null ? null : lowerBlock(t.finallyBlock())); }
        if (statement instanceof ThrowStmt t) return new SolvikStmt.Throw(lower(t.value(), null));
        if (statement instanceof BreakStmt) return new SolvikStmt.Break();
        if (statement instanceof ContinueStmt) return new SolvikStmt.Continue();
        if (statement instanceof BlockStmt b) return new SolvikStmt.Block(lowerBlock(b.block()));
        throw new IllegalStateException("unlowered statement: " + statement);
    }

    private void emitStmt(SolvikStmt statement) {
        if (statement instanceof SolvikStmt.VarDecl d) {
            // A match used as a value is lowered to an if/else chain that assigns
            // the result, avoiding an allocating Supplier lambda per evaluation.
            if (d.initializer() instanceof SolvikIr.Match m) { line(javaType(d.type()) + " " + localName(d.name()) + ";"); emitMatchHoisted(m, localName(d.name()), false); return; }
            line(javaType(d.type()) + " " + localName(d.name()) + (d.initializer() == null ? ";" : " = " + emitIr(d.initializer()) + ";"));
        }
        else if (statement instanceof SolvikStmt.Expr e) {
            if (e.expression() instanceof SolvikIr.Assign a && a.value() instanceof SolvikIr.Match m && hoistableMatchTarget(a.target())) { emitMatchHoisted(m, emitIr(a.target()), false); return; }
            line(emitIr(e.expression()) + ";");
        }
        else if (statement instanceof SolvikStmt.Return r) {
            if (r.value() instanceof SolvikIr.Match m) { emitMatchHoisted(m, null, true); return; }
            line(r.value() == null ? "return;" : "return " + emitIr(r.value()) + ";");
        }
        else if (statement instanceof SolvikStmt.If i) { line("if (" + emitIr(i.condition()) + ") {"); indent(); for (SolvikStmt s : i.thenBranch()) emitStmt(s); outdent(); line("}"); if (!i.elseBranch().isEmpty()) { line("else {"); indent(); for (SolvikStmt s : i.elseBranch()) emitStmt(s); outdent(); line("}"); } }
        else if (statement instanceof SolvikStmt.While w) { line("while (" + emitIr(w.condition()) + ") {"); indent(); for (SolvikStmt s : w.body()) emitStmt(s); outdent(); line("}"); }
        else if (statement instanceof SolvikStmt.ForRange f) { String cmp = f.inclusive() ? " <= " : " < "; line("for (" + javaType(f.loopType()) + " " + localName(f.name()) + " = " + emitIr(f.start()) + "; " + localName(f.name()) + cmp + emitIr(f.end()) + "; " + localName(f.name()) + "++) {"); indent(); for (SolvikStmt s : f.body()) emitStmt(s); outdent(); line("}"); }
        else if (statement instanceof SolvikStmt.ForEach f) { String expression = f.iterable().type() != null && f.iterable().type().base() == Base.STRING ? "RT.codePoints(" + emitIr(f.iterable()) + ")" : emitIr(f.iterable()); line("for (" + javaType(f.elementType(), true) + " " + localName(f.name()) + " : " + expression + ") {"); indent(); for (SolvikStmt s : f.body()) emitStmt(s); outdent(); line("}"); }
        else if (statement instanceof SolvikStmt.Switch s) {
            List<List<Long>> constantCases = constantIntegerCases(s);
            if (constantCases != null) { emitJavaSwitch(s, constantCases); return; }
            String subject = "__switch" + temp++; line((s.directEquality() ? javaType(s.subjectType()) : "Object") + " " + subject + " = " + emitIr(s.subject()) + ";"); boolean first = true; for (SolvikStmt.SwitchCase c : s.cases()) { String condition = c.isDefault() ? "true" : c.values().stream().map(v -> s.directEquality() ? JavaIr.render(equality(BinaryOp.EQ, false, false, JavaIr.atom(subject, s.subjectType()), javaLower(v), s.subjectType(), v.type(), named(Base.BOOLEAN, "Boolean"))) : "RT.eq(" + subject + ", " + emitIr(v) + ")").reduce((a,b)->a+" || "+b).orElse("false"); line(!first && condition.equals("true") ? "else {" : (first ? "if" : "else if") + " (" + unparenthesize(condition) + ") {"); indent(); for (SolvikStmt st : c.body()) emitStmt(st); outdent(); line("}"); first = false; } }
        else if (statement instanceof SolvikStmt.Try t) { line("try {"); indent(); for (SolvikStmt st : t.body()) emitStmt(st); outdent(); line("}"); if (!t.catches().isEmpty()) { line("catch (RT.Thrown __caught) {"); indent(); for (int i = 0; i < t.catches().size(); i++) { SolvikStmt.Catch c = t.catches().get(i); String type = javaType(c.type()); String condition = c.type().base() == Base.THROWABLE ? "true" : "__caught.value instanceof " + type; line((i == 0 ? "if" : "else if") + " (" + condition + ") {"); indent(); line(type + " " + localName(c.name()) + " = " + (type.equals("Object") ? "__caught.value" : "(" + type + ") __caught.value") + ";"); for (SolvikStmt st : c.body()) emitStmt(st); outdent(); line("}"); } line("else throw __caught;"); outdent(); line("}"); } if (t.finallyBlock() != null) { line("finally {"); indent(); for (SolvikStmt st : t.finallyBlock()) emitStmt(st); outdent(); line("}"); } }
        else if (statement instanceof SolvikStmt.Throw t) line((emittingStaticBlock ? "if (RT.always()) " : "") + "throw new RT.Thrown(" + emitIr(t.value()) + ");");
        else if (statement instanceof SolvikStmt.Break) line("break;");
        else if (statement instanceof SolvikStmt.Continue) line("continue;");
        else if (statement instanceof SolvikStmt.Block b) { line("{"); indent(); for (SolvikStmt s : b.statements()) emitStmt(s); outdent(); line("}"); }
        else if (statement instanceof SolvikStmt.MatchStmt m) emitMatchStmt(m);
    }

    private Type iterableElement(Type t) { return switch (t.base()) { case STRING -> named(Base.CHAR, "Char"); case RANGE -> named(Base.LONG, "Long"); default -> t.args().isEmpty() ? named(Base.OBJECT, "Object") : t.args().get(0); }; }

    /**
     * Case values as compile-time constants when the switch can lower to a Java
     * {@code switch} statement, or null when it must stay an if/else chain
     * (non-Integer subject, non-constant case values, duplicate values, or a
     * value outside the int range). Only Integer subjects are lowered: some
     * recent javac builds parse constant-case switches over {@code long} as the
     * preview "primitive patterns" feature, so Long switches stay if/else.
     */
    private List<List<Long>> constantIntegerCases(SolvikStmt.Switch s) {
        Type subjectType = s.subjectType();
        if (subjectType == null || subjectType.nullable() || subjectType.base() != Base.INTEGER) return null;
        for (SolvikStmt.SwitchCase c : s.cases()) if (hasLoopEscape(c.body())) return null;
        List<List<Long>> result = new ArrayList<>();
        Set<Long> seen = new HashSet<>();
        int defaults = 0;
        for (SolvikStmt.SwitchCase c : s.cases()) {
            if (c.isDefault()) { if (++defaults > 1) return null; result.add(List.of()); continue; }
            List<Long> caseValues = new ArrayList<>(c.values().size());
            for (SolvikIr value : c.values()) {
                Long constant = constantCaseValue(value);
                if (constant == null || !seen.add(constant)) return null;
                caseValues.add(constant);
            }
            result.add(caseValues);
        }
        return result;
    }

    /** The exact value of a constant integer case expression that fits in an int, or null otherwise. */
    private Long constantCaseValue(SolvikIr expression) {
        if (expression instanceof SolvikIr.Coerce c) expression = c.value();
        if (!(expression instanceof SolvikIr.Literal l) || l.kind() != LiteralKind.INT) return null;
        try {
            BigInteger value = new BigInteger(SemanticAnalyzer.cleanInteger(l.text()));
            if (value.compareTo(BigInteger.valueOf(Integer.MIN_VALUE)) < 0 || value.compareTo(BigInteger.valueOf(Integer.MAX_VALUE)) > 0) return null;
            return value.longValue();
        } catch (RuntimeException e) { return null; }
    }

    /** Emits a Java switch statement; case bodies that do not diverge get an explicit break. */
    private void emitJavaSwitch(SolvikStmt.Switch s, List<List<Long>> constantCases) {
        String subject = "__switch" + temp++;
        line(javaType(s.subjectType()) + " " + subject + " = " + emitIr(s.subject()) + ";");
        line("switch (" + subject + ") {"); indent();
        for (int i = 0; i < s.cases().size(); i++) {
            SolvikStmt.SwitchCase c = s.cases().get(i);
            if (c.isDefault()) line("default:");
            else for (Long value : constantCases.get(i)) line("case " + value + ":");
            indent();
            for (SolvikStmt st : c.body()) emitStmt(st);
            if (!blockDiverges(c.body())) line("break;");
            outdent();
        }
        outdent(); line("}");
    }

    /** Conservative divergence test used only to decide whether a switch case needs a break. */
    private boolean blockDiverges(List<SolvikStmt> statements) {
        return !statements.isEmpty() && stmtDiverges(statements.get(statements.size() - 1));
    }

    /**
     * True when the statements contain a break/continue that binds to an
     * enclosing loop. Inside a Java switch such a statement would bind to the
     * switch instead, so those switches must stay if/else chains. Breaks and
     * continues inside nested loops bind to those loops and are ignored.
     */
    private boolean hasLoopEscape(List<SolvikStmt> statements) {
        for (SolvikStmt statement : statements) {
            if (statement instanceof SolvikStmt.Break || statement instanceof SolvikStmt.Continue) return true;
            if (statement instanceof SolvikStmt.Block b) { if (hasLoopEscape(b.statements())) return true; }
            else if (statement instanceof SolvikStmt.If i) { if (hasLoopEscape(i.thenBranch()) || hasLoopEscape(i.elseBranch())) return true; }
            else if (statement instanceof SolvikStmt.Try t) {
                if (hasLoopEscape(t.body())) return true;
                for (SolvikStmt.Catch c : t.catches()) if (hasLoopEscape(c.body())) return true;
                if (t.finallyBlock() != null && hasLoopEscape(t.finallyBlock())) return true;
            }
            // While/ForRange/ForEach bodies bind their own break/continue.
        }
        return false;
    }

    private boolean stmtDiverges(SolvikStmt statement) {
        if (statement instanceof SolvikStmt.Return || statement instanceof SolvikStmt.Throw || statement instanceof SolvikStmt.Break || statement instanceof SolvikStmt.Continue) return true;
        if (statement instanceof SolvikStmt.Block b) return blockDiverges(b.statements());
        if (statement instanceof SolvikStmt.If i) return blockDiverges(i.thenBranch()) && !i.elseBranch().isEmpty() && blockDiverges(i.elseBranch());
        return false;
    }
    private boolean directEqualityType(Type type) {
        return type != null && !type.nullable() && (type.base() == Base.BOOLEAN || type.base() == Base.STRING
                || type.base() == Base.CHAR || type.numeric());
    }


    /** Lower an expression in a value context, inserting an explicit coercion when required. */
    private SolvikIr lowerValue(Expr expression, Type expected) {
        SolvikIr value = lower(expression, expected);
        Type actual = model.type(expression);
        if (expected != null && actual != null && !(expression instanceof Literal) && (expected.base() == Base.BYTE || expected.base() == Base.SHORT) && actual.integral() && actual.base() != expected.base() && !expected.nullable() && model.constantInteger(expression) != null) {
            return new SolvikIr.Coerce(value, actual, expected, true);
        }
        if (expected == null || actual == null || expression instanceof Literal || !actual.primitive() || !expected.primitive() || actual.base() == expected.base()) return value;
        if (!numericWidening(actual.base(), expected.base())) return value;
        return new SolvikIr.Coerce(value, actual, expected, false);
    }

    /** AST expression -> resolved Solvik IR (the semantic boundary). */
    private SolvikIr lower(Expr expression, Type expected) {
        if (expression instanceof NameExpr n) {
            if (n.name().equals("self")) return new SolvikIr.Self(model.type(n));
            if (model.fieldNames.containsKey(n)) { SemanticAnalyzer.FieldInfo info = model.fieldNames.get(n); return new SolvikIr.Field(owner, n.name(), info.declaration.isStatic(), model.type(n)); }
            if (model.structs.containsKey(owner) && model.structs.get(owner).fields.containsKey(n.name()) && model.structs.get(owner).fields.get(n.name()).declaration.isStatic()) return new SolvikIr.Field(owner, n.name(), true, model.type(n));
            return new SolvikIr.Local(localRenames.getOrDefault(n.name(), n.name()), model.type(n));
        }
        if (expression instanceof UnaryExpr u) return lowerUnary(u);
        if (expression instanceof BinaryExpr b) return lowerBinary(b);
        if (expression instanceof CoalesceExpr c) return new SolvikIr.Coalesce(lower(c.left(), null), lower(c.right(), model.type(c.left()).nonNull()), model.type(c));
        if (expression instanceof RangeExpr r) return new SolvikIr.Range(lower(r.start(), named(Base.LONG, "Long")), lower(r.end(), named(Base.LONG, "Long")), r.inclusive(), model.type(r));
        if (expression instanceof Literal l) return new SolvikIr.Literal(l.kind(), l.text(), expected != null ? expected : model.type(l));
        if (expression instanceof ListExpr l) { Type inferred = model.type(l); Type element = expected != null && expected.base() == Base.LIST && !expected.args().isEmpty() ? expected.args().get(0) : inferred.args().isEmpty() ? named(Base.OBJECT, "Object") : inferred.args().get(0); return new SolvikIr.ListLiteral(l.elements().stream().map(x -> lower(x, element)).toList(), element, inferred); }
        if (expression instanceof MapExpr m) { Type mapType = expected != null && expected.base() == Base.MAP ? expected : model.type(m); Type key = mapType.args().size()>0?mapType.args().get(0):named(Base.OBJECT,"Object"); Type value = mapType.args().size()>1?mapType.args().get(1):named(Base.OBJECT,"Object"); return new SolvikIr.MapLiteral(m.entries().stream().map(x -> java.util.Map.entry(lower(x.key(), key), lower(x.value(), value))).toList(), key, value, model.type(m)); }
        if (expression instanceof MemberExpr m) return new SolvikIr.Member(lower(m.object(), null), m.name(), model.memberFields.containsKey(m), model.type(m));
        if (expression instanceof StaticExpr s) return new SolvikIr.StaticRef(s.name(), typeOf(s.type()));
        if (expression instanceof AssignExpr a) return new SolvikIr.Assign(lower(a.target(), null), lower(a.value(), model.type(a.target())), model.type(a));
        if (expression instanceof CallExpr c) return lowerCall(c);
        if (expression instanceof UpdateExpr u) { Type t = model.type(u); Type valueType = model.type(u.value()); if (u.op() == BinaryOp.CONCAT) return new SolvikIr.Update(u.op(), lower(u.target(), null), lower(u.value(), named(Base.STRING, "String")), t, t, valueType); Type promoted = binaryPromotion(t, valueType); if (promoted == null) promoted = t; return new SolvikIr.Update(u.op(), lower(u.target(), null), lower(u.value(), promoted), promoted, t, valueType); }
        if (expression instanceof SelfInitExpr s) { StructDecl declaration = model.structs.get(owner).declaration; java.util.Map<String, Expr> values = new HashMap<>(); for (FieldInit f : s.fields()) values.put(f.name(), f.value()); List<SolvikIr> args = new ArrayList<>(); for (FieldDecl f : declaration.fields()) if (!f.isStatic()) args.add(values.containsKey(f.name()) ? lower(values.get(f.name()), typeOf(f.type())) : new SolvikIr.DefaultValue(typeOf(f.type()))); return new SolvikIr.SelfInit(owner, args, model.type(s)); }
        if (expression instanceof MatchExpr m) { Type subjectType = model.type(m.subject()); List<SolvikIr.MatchArm> arms = new ArrayList<>(); for (MatchArm arm : m.arms()) arms.add(new SolvikIr.MatchArm(lowerPattern(arm.pattern(), subjectType), lower(arm.body(), model.type(m)))); return new SolvikIr.Match(lower(m.subject(), null), arms, model.type(m)); }
        return new SolvikIr.Literal(LiteralKind.NULL, "null", named(Base.OBJECT, "Object"));
    }

    private SolvikIr lowerUnary(UnaryExpr u) {
        Type operandType = model.type(u.operand());
        return new SolvikIr.Unary(u.op(), lower(u.operand(), operandType), operandType, model.type(u));
    }

    private SolvikIr lowerBinary(BinaryExpr b) {
        Type result = model.type(b), leftType = model.type(b.left()), rightType = model.type(b.right());
        return new SolvikIr.Binary(b.op(), lower(b.left(), result), lower(b.right(), result), leftType, rightType, result);
    }

    /** Resolved Solvik IR -> Java expression IR (the backend boundary). */
    private JavaIr javaLower(SolvikIr expression) {
        if (expression instanceof SolvikIr.Self s) return JavaIr.atom("this", s.type());
        if (expression instanceof SolvikIr.Local l) return JavaIr.atom(localName(l.name()), l.type());
        if (expression instanceof SolvikIr.Field f) return JavaIr.atom((f.isStatic() ? structNames.get(f.owner()) + "." : "this.") + fieldName(f.name()), f.type());
        if (expression instanceof SolvikIr.Literal l) return JavaIr.atom(literalJava(l.kind(), l.text(), l.type()), l.type());
        if (expression instanceof SolvikIr.ListLiteral l) return JavaIr.call("RT.<" + javaType(l.elementType(), true) + ">list", l.elements().stream().map(this::javaLower).toList(), l.type());
        if (expression instanceof SolvikIr.MapLiteral m) { List<JavaIr> args = new ArrayList<>(); for (java.util.Map.Entry<SolvikIr, SolvikIr> entry : m.entries()) { args.add(javaLower(entry.getKey())); args.add(javaLower(entry.getValue())); } return JavaIr.call("RT.<" + javaType(m.keyType(), true) + ", " + javaType(m.valueType(), true) + ">map", args, m.type()); }
        if (expression instanceof SolvikIr.Member m) {
            JavaIr receiver = m.receiver().type() != null && m.receiver().type().nullable()
                    ? JavaIr.call("RT.require", List.of(javaLower(m.receiver())), m.receiver().type())
                    : javaLower(m.receiver());
            return JavaIr.fieldAccess(receiver, m.isField() ? fieldName(m.name()) : methodName(m.name()), m.type());
        }
        if (expression instanceof SolvikIr.StaticRef s) return staticRefIr(s.name(), s.type());
        if (expression instanceof SolvikIr.Assign a) return JavaIr.atom(emitIr(a.target()) + " = " + emitIr(a.value()), a.type());
        if (expression instanceof SolvikIr.DefaultValue d) return JavaIr.atom(defaultValue(d.type()), d.type());
        if (expression instanceof SolvikIr.Coerce c) { JavaIr value = javaLower(c.value()); Type to = c.to(); if (c.constantInteger()) return JavaIr.cast(to.base() == Base.BYTE ? "byte" : "short", value, to); if (to.nullable()) { String wrapper = switch (to.base()) { case LONG -> "Long"; case FLOAT -> "Float"; case DOUBLE -> "Double"; case INTEGER -> "Integer"; case SHORT -> "Short"; case BYTE -> "Byte"; default -> null; }; if (wrapper != null) return JavaIr.call(wrapper + ".valueOf", List.of(JavaIr.cast(primitiveCast(to.base()), value, to)), to); return value; } return JavaIr.cast(primitiveCast(to.base()), value, to); }
        if (expression instanceof SolvikIr.SelfInit s) {
            List<JavaIr> args = new ArrayList<>();
            for (SolvikIr value : s.values()) args.add(javaLower(value));
            String type = structNames.get(s.owner()) + typeArgumentsOf(model.structs.get(s.owner()).declaration.typeParams());
            return JavaIr.newExpression(type, args, s.type());
        }
        if (expression instanceof SolvikIr.Call c) return JavaIr.atom(c.builtin() != null ? javaBuiltin(c) : javaCall(c), c.type());
        if (expression instanceof SolvikIr.Update u) {
            JavaIr target = javaLower(u.target());
            Type t = u.targetType();
            if (u.op() == BinaryOp.CONCAT) return JavaIr.atom(emitJavaIr(target) + " = " + emitJavaIr(concatenation(target, javaLower(u.value()), t, u.valueType(), t)), t);
            JavaIr operation = arithmetic(u.op(), target, javaLower(u.value()), u.promoted(), t);
            // Java performs the compound operation in the promoted type and narrows back; Solvik requires that narrowing to be checked.
            if (t.base() == Base.BYTE || t.base() == Base.SHORT) operation = JavaIr.call(t.base() == Base.BYTE ? "RT.convertByte" : "RT.convertShort", List.of(operation), t);
            return JavaIr.atom(emitJavaIr(target) + " = " + emitJavaIr(operation), t);
        }
        if (expression instanceof SolvikIr.Unary u) return javaUnary(u);
        if (expression instanceof SolvikIr.Binary b) return javaBinary(b);
        if (expression instanceof SolvikIr.Coalesce c) { JavaIr l = javaLower(c.left()); JavaIr r = javaLower(c.right()); Type t = c.type(); return JavaIr.paren(JavaIr.ternary(JavaIr.infix("!=", l, JavaIr.atom("null", t), t), l, r, t), t); }
        if (expression instanceof SolvikIr.Range r) return JavaIr.call("RT.range", List.of(javaLower(r.start()), javaLower(r.end()), JavaIr.atom(Boolean.toString(r.inclusive()), named(Base.BOOLEAN, "Boolean"))), r.type());
        if (expression instanceof SolvikIr.Match m) return JavaIr.atom(javaMatch(m), m.type());
        throw new IllegalStateException("unknown Solvik IR node: " + expression);
    }

    private JavaIr javaUnary(SolvikIr.Unary u) {
        JavaIr x = javaLower(u.operand()); Type t = u.operandType(); Type result = u.type();
        if (u.op() == UnaryOp.NOT) return JavaIr.paren(JavaIr.prefix("!", x, result), result);
        if (t.base() == Base.INTEGER || t.base() == Base.BYTE || t.base() == Base.SHORT) return JavaIr.staticMethod("Math", "negateExact", List.of(x), result);
        if (t.base() == Base.LONG) return JavaIr.staticMethod("Math", "negateExact", List.of(x), result);
        if (t.base() == Base.BIG_INTEGER || t.base() == Base.BIG_DECIMAL) return JavaIr.method(JavaIr.paren(x, t), "negate", List.of(), result);
        return JavaIr.paren(JavaIr.prefix("-", x, result), result);
    }

    private JavaIr javaBinary(SolvikIr.Binary b) {
        JavaIr l = javaLower(b.left()), r = javaLower(b.right());
        Type result = b.type(), leftType = b.leftType(), rightType = b.rightType();
        return switch (b.op()) {
            case AND -> JavaIr.paren(JavaIr.infix("&&", l, r, result), result);
            case OR -> JavaIr.paren(JavaIr.infix("||", l, r, result), result);
            case CONCAT -> result.base() == Base.RANGE
                    ? JavaIr.call("RT.range", List.of(l, r, JavaIr.atom("false", named(Base.BOOLEAN, "Boolean"))), result)
                    : concatenation(l, r, leftType, rightType, result);
            case ADD, SUB, MUL, DIV, MOD -> arithmetic(b.op(), l, r, result, leftType);
            case EQ, NE -> enumVariantEquality(b, l, r, leftType, rightType, result);
            case LT, LE, GT, GE -> comparison(b.op(), l, r, result, leftType, rightType);
        };
    }

    private boolean isNullIr(SolvikIr expression) { return expression instanceof SolvikIr.Literal l && l.kind() == LiteralKind.NULL; }

    /**
     * Equality where one operand is a payload-free enum variant: the resolved tag
     * makes a direct tag comparison both safe and exact, so no structural
     * {@code RT.eq} dispatch is needed. Payload variants and nullable subjects keep
     * the semantic helper.
     */
    private JavaIr enumVariantEquality(SolvikIr.Binary b, JavaIr l, JavaIr r, Type leftType, Type rightType, Type result) {
        int leftTag = enumVariantTag(b.left(), leftType);
        int rightTag = enumVariantTag(b.right(), rightType);
        boolean notEqual = b.op() == BinaryOp.NE;
        if (leftTag >= 0 && rightTag < 0 && isExactEnumType(rightType, leftType)) return JavaIr.atom("(" + emitJavaIr(r) + ".tag() " + (notEqual ? "!=" : "==") + " " + leftTag + ")", result);
        if (rightTag >= 0 && leftTag < 0 && isExactEnumType(leftType, rightType)) return JavaIr.atom("(" + emitJavaIr(l) + ".tag() " + (notEqual ? "!=" : "==") + " " + rightTag + ")", result);
        return equality(b.op(), isNullIr(b.left()), isNullIr(b.right()), l, r, leftType, rightType, result);
    }

    private int enumVariantTag(SolvikIr expression, Type type) {
        if (!(expression instanceof SolvikIr.StaticRef s) || type == null || type.base() != Base.ENUM || !model.enums.containsKey(type.name())) return -1;
        List<VariantDecl> variants = model.enums.get(type.name()).declaration.variants();
        for (int i = 0; i < variants.size(); i++) if (variants.get(i).name().equals(s.name())) return variants.get(i).payload() == null ? i : -1;
        return -1;
    }

    private boolean isExactEnumType(Type candidate, Type variantType) {
        return candidate != null && !candidate.nullable() && candidate.base() == Base.ENUM && variantType != null && candidate.name().equals(variantType.name());
    }

    private JavaIr arithmetic(BinaryOp op, JavaIr l, JavaIr r, Type result, Type left) {
        // Checked integral overflow is a Solvik semantic, and Math.addExact and
        // friends express exactly that with a standard Java 17 intrinsic, so
        // addition/subtraction/multiplication lower directly to the JDK instead
        // of a custom RT wrapper. Division and remainder still need an explicit
        // MIN_VALUE / -1 overflow check and therefore keep a narrow helper.
        if ((op == BinaryOp.ADD || op == BinaryOp.SUB || op == BinaryOp.MUL) && result.base() == Base.INTEGER)
            return JavaIr.staticMethod("Math", exactMethod(op), List.of(l, r), result);
        if ((op == BinaryOp.ADD || op == BinaryOp.SUB || op == BinaryOp.MUL) && result.base() == Base.LONG)
            return JavaIr.staticMethod("Math", exactMethod(op), List.of(l, r), result);
        String suffix = switch (op) { case ADD -> "add"; case SUB -> "sub"; case MUL -> "mul"; case DIV -> "div"; default -> "rem"; };
        if (result.base() == Base.INTEGER) return JavaIr.call("RT." + suffix + "Int", List.of(l, r), result);
        if (result.base() == Base.LONG) return JavaIr.call("RT." + suffix + "Long", List.of(l, r), result);
        if (result.base() == Base.BIG_INTEGER) return JavaIr.method(JavaIr.paren(l, left), bigMethod(op), List.of(r), result);
        if (result.base() == Base.BIG_DECIMAL) return op == BinaryOp.DIV
                ? JavaIr.method(JavaIr.paren(l, left), "divide", List.of(r, JavaIr.atom("MathContext.DECIMAL128", result)), result)
                : JavaIr.method(JavaIr.paren(l, left), bigMethod(op), List.of(r), result);
        return JavaIr.paren(JavaIr.infix(switch (op) { case ADD -> "+"; case SUB -> "-"; case MUL -> "*"; case DIV -> "/"; default -> "%"; }, l, r, result), result);
    }
    private String exactMethod(BinaryOp op) { return switch (op) { case ADD -> "addExact"; case SUB -> "subtractExact"; default -> "multiplyExact"; }; }
    private String bigMethod(BinaryOp op) { return switch (op) { case ADD -> "add"; case SUB -> "subtract"; case MUL -> "multiply"; case DIV -> "divide"; default -> "remainder"; }; }
    private JavaIr comparison(BinaryOp op, JavaIr l, JavaIr r, Type result, Type left, Type right) {
        String operator = switch (op) { case LT -> "<"; case LE -> "<="; case GT -> ">"; default -> ">="; };
        if (result.base() == Base.BOOLEAN && !left.nullable() && !right.nullable() && left.base() == Base.STRING && right.base() == Base.STRING)
            return JavaIr.paren(JavaIr.infix(operator, JavaIr.method(l, "compareTo", List.of(r), result), JavaIr.atom("0", result), result), result);
        if (result.base() == Base.BOOLEAN && !left.nullable() && !right.nullable() && (left.base() == Base.BIG_INTEGER || left.base() == Base.BIG_DECIMAL) && left.base() == right.base())
            return JavaIr.paren(JavaIr.infix(operator, JavaIr.method(l, "compareTo", List.of(r), result), JavaIr.atom("0", result), result), result);
        if (result.base() == Base.BOOLEAN && (left.base() == Base.STRING || left.base() == Base.BIG_INTEGER || left.base() == Base.BIG_DECIMAL))
            return JavaIr.paren(JavaIr.infix(operator, JavaIr.call("RT.compare", List.of(l, r), result), JavaIr.atom("0", result), result), result);
        if (result.base() == Base.BOOLEAN) return JavaIr.paren(JavaIr.infix(operator, l, r, result), result);
        return JavaIr.atom("false", result);
    }
    private JavaIr equality(BinaryOp op, boolean leftNull, boolean rightNull, JavaIr l, JavaIr r, Type left, Type right, Type result) {
        boolean notEqual = op == BinaryOp.NE;
        JavaIr expression;
        if ((leftNull && javaReference(right)) || (rightNull && javaReference(left))) {
            // RT.eq(x, null) is exactly a reference comparison; emit it directly.
            return JavaIr.paren(JavaIr.infix(notEqual ? "!=" : "==", l, r, result), result);
        } else if (!left.nullable() && !right.nullable() && left.base() == Base.BOOLEAN && right.base() == Base.BOOLEAN) {
            expression = JavaIr.paren(JavaIr.infix("==", l, r, result), result);
        } else if (!left.nullable() && !right.nullable() && left.base() == Base.STRING && right.base() == Base.STRING) {
            expression = JavaIr.method(l, "equals", List.of(r), result);
        } else if (!left.nullable() && !right.nullable() && left.base() == Base.CHAR && right.base() == Base.CHAR) {
            expression = JavaIr.method(l, "equals", List.of(r), result);
        } else if ((left.base() == Base.STRING && right.base() == Base.STRING) || (left.base() == Base.CHAR && right.base() == Base.CHAR)) {
            // Objects.equals is exactly RT.eq for strings/chars, including the
            // null cases, so a nullable operand no longer needs the runtime call.
            expression = JavaIr.call("Objects.equals", List.of(l, r), result);
        } else {
            Type promoted = left.numeric() && right.numeric() ? binaryPromotion(left, right) : null;
            if (!left.nullable() && !right.nullable() && promoted != null && promoted.primitive() && promoted.base() != Base.CHAR) {
                expression = JavaIr.paren(JavaIr.infix("==", l, r, result), result);
            } else {
                expression = JavaIr.call("RT.eq", List.of(box(l, left), box(r, right)), result);
            }
        }
        return notEqual ? JavaIr.paren(JavaIr.prefix("!", expression, result), result) : expression;
    }

    private JavaIr concatenation(JavaIr l, JavaIr r, Type left, Type right, Type result) {
        if (!left.nullable() && !right.nullable() && (left.base() == Base.STRING || left.base() == Base.CHAR) && (right.base() == Base.STRING || right.base() == Base.CHAR))
            return JavaIr.paren(JavaIr.infix("+", l, r, result), result);
        // Java's built-in string conversion is identical to RT.format for these
        // types (including null rendering as "null"), so emit a direct concatenation
        // and skip the RT.cat boxing/dispatch. Float/Double are excluded because
        // RT.format strips trailing zeros; Object is excluded because it may hold
        // one of those at runtime.
        if (javaStringOperand(left) && formatCompatible(right) || javaStringOperand(right) && formatCompatible(left))
            return JavaIr.paren(JavaIr.infix("+", l, r, result), result);
        return JavaIr.call("RT.cat", List.of(l, r), result);
    }

    private boolean javaStringOperand(Type type) { return type.base() == Base.STRING || type.base() == Base.CHAR; }

    private boolean formatCompatible(Type type) {
        return switch (type.base()) {
            case BOOLEAN, BYTE, SHORT, INTEGER, LONG, BIG_INTEGER, BIG_DECIMAL, STRING, CHAR, STRUCT, TRAIT, ENUM -> true;
            default -> false;
        };
    }
    private JavaIr box(JavaIr x, Type t) { return t.primitive() && !t.nullable() ? switch (t.base()) { case BYTE -> JavaIr.call("Byte.valueOf", List.of(x), t); case SHORT -> JavaIr.call("Short.valueOf", List.of(x), t); case INTEGER -> JavaIr.call("Integer.valueOf", List.of(x), t); case LONG -> JavaIr.call("Long.valueOf", List.of(x), t); case FLOAT -> JavaIr.call("Float.valueOf", List.of(x), t); case DOUBLE -> JavaIr.call("Double.valueOf", List.of(x), t); case BOOLEAN -> JavaIr.call("Boolean.valueOf", List.of(x), t); default -> x; } : x; }
    private boolean javaReference(Type t) { return t.nullable() || t.base() == Base.CHAR || !t.primitive(); }

    private SolvikIr lowerCall(CallExpr call) {
        SemanticAnalyzer.CallInfo info = model.calls.get(call);
        if (info == null) return new SolvikIr.Literal(LiteralKind.NULL, "null", named(Base.OBJECT, "Object"));
        SolvikIr receiver = null; Type staticOwnerType = null; boolean staticTypeArguments = false; String implicitOwner = null; boolean implicitInstance = false; String name;
        if (call.callee() instanceof StaticExpr s) { staticOwnerType = typeOf(s.type()); staticTypeArguments = info.method() != null && !info.method().declaration.instance() && info.receiverType() != null && !info.receiverType().args().isEmpty(); name = s.name(); }
        else if (call.callee() instanceof MemberExpr m) { receiver = lower(m.object(), null); name = m.name(); }
        else { name = ((NameExpr) call.callee()).name(); implicitOwner = owner; implicitInstance = currentMethod != null && currentMethod.instance(); }
        List<SolvikIr> arguments = info.builtin() != null ? lowerBuiltinArguments(call, info) : lowerCallArguments(call, info);
        return new SolvikIr.Call(receiver, staticOwnerType, staticTypeArguments, implicitOwner, implicitInstance, name, info.builtin(), arguments, info.receiverType(), model.type(call));
    }

    private List<SolvikIr> lowerCallArguments(CallExpr call, SemanticAnalyzer.CallInfo info) {
        List<Expr> ordered = info.orderedArguments(); List<SolvikIr> result = new ArrayList<>();
        if (info.method() != null && info.variadic()) {
            MethodDecl method = info.method().declaration; int fixed = method.params().size() - 1;
            for (int i = 0; i < fixed && i < ordered.size(); i++) result.add(lowerValue(ordered.get(i), callParameterType(info, method.params().get(i).type())));
            Type element = callParameterType(info, method.params().get(method.params().size()-1).type());
            if (ordered.size() == fixed + 1 && call.arguments().stream().anyMatch(a -> a.spread() && a.expression() == ordered.get(fixed))) result.add(lowerValue(ordered.get(fixed), genericListType(element)));
            else { List<SolvikIr> rest = new ArrayList<>(); for (int i = fixed; i < ordered.size(); i++) rest.add(lowerValue(ordered.get(i), element)); result.add(new SolvikIr.ListLiteral(rest, element, genericListType(element))); }
        } else if (info.method() != null) {
            List<Param> params = info.method().declaration.params();
            for (int i = 0; i < ordered.size(); i++) result.add(lowerValue(ordered.get(i), i < params.size() ? callParameterType(info, params.get(i).type()) : null));
        } else {
            for (Expr argument : ordered) result.add(lowerValue(argument, null));
        }
        return result;
    }

    private List<SolvikIr> lowerBuiltinArguments(CallExpr call, SemanticAnalyzer.CallInfo info) {
        String builtin = info.builtin(); List<SolvikIr> result = new ArrayList<>();
        if (builtin.startsWith("enum:")) {
            String variant = builtin.substring(5); Type payload = null;
            if (info.receiverType() != null && model.enums.containsKey(info.receiverType().name())) for (VariantDecl candidate : model.enums.get(info.receiverType().name()).declaration.variants()) if (candidate.name().equals(variant) && candidate.payload() != null) payload = enumPayloadType(candidate.payload(), info.receiverType());
            for (Arg argument : call.arguments()) result.add(lowerValue(argument.expression(), payload));
            return result;
        }
        if (builtin.startsWith("object:") || builtin.startsWith("dynamic:")) { for (Arg argument : call.arguments()) result.add(lowerValue(argument.expression(), null)); return result; }
        int dot = builtin.indexOf('.'); String namespace = dot < 0 ? builtin : builtin.substring(0, dot); String method = dot < 0 ? builtin : builtin.substring(dot + 1);
        if (call.callee() instanceof MemberExpr) { for (int i = 0; i < call.arguments().size(); i++) result.add(lowerValue(call.arguments().get(i).expression(), builtinArgumentType(info.receiverType(), method, i))); return result; }
        if (namespace.equals("Math") && method.equals("abs") && !call.arguments().isEmpty()) { Type argument = model.type(call.arguments().get(0).expression()); if (argument.base() == Base.LONG) { result.add(lowerValue(call.arguments().get(0).expression(), argument)); return result; } if (argument.integral()) { result.add(lowerValue(call.arguments().get(0).expression(), named(Base.INTEGER, "Integer"))); return result; } }
        for (Arg argument : call.arguments()) result.add(lowerValue(argument.expression(), null));
        return result;
    }

    private Type callParameterType(SemanticAnalyzer.CallInfo info, TypeRef ref) {
        if (ref == null) return named(Base.VOID, "Void");
        if (info.receiverType() != null && info.method() != null) {
            List<TypeParam> ownerParams = model.structs.containsKey(info.method().owner)
                    ? model.structs.get(info.method().owner).declaration.typeParams()
                    : model.traits.containsKey(info.method().owner) ? model.traits.get(info.method().owner).declaration.typeParams() : List.of();
            for (int i = 0; i < ownerParams.size() && i < info.receiverType().args().size(); i++) if (ownerParams.get(i).name().equals(ref.name())) return info.receiverType().args().get(i);
        }
        if (ref.name().equals("Self") && info.receiverType() != null) return info.receiverType();
        List<Type> args = ref.args().stream().map(x -> callParameterType(info, x)).toList();
        Type t = fromName(ref.name(), args, ref.nullable());
        if (t.base() == Base.UNKNOWN) {
            if (model.structs.containsKey(ref.name())) t = new Type(Base.STRUCT, ref.name(), args, ref.nullable());
            else if (model.traits.containsKey(ref.name())) t = new Type(Base.TRAIT, ref.name(), args, ref.nullable());
            else if (model.enums.containsKey(ref.name())) t = new Type(Base.ENUM, ref.name(), args, ref.nullable());
        }
        return t;
    }
    private Type genericListType(Type element) { return generic(Base.LIST, "List", List.of(element)); }
    private Type enumPayloadType(TypeRef ref, Type enumType) {
        List<TypeParam> parameters = model.enums.containsKey(enumType.name()) ? model.enums.get(enumType.name()).declaration.typeParams() : List.of();
        for (int i = 0; i < parameters.size() && i < enumType.args().size(); i++) if (parameters.get(i).name().equals(ref.name())) return enumType.args().get(i);
        List<Type> args = ref.args().stream().map(x -> enumPayloadType(x, enumType)).toList();
        Type t = fromName(ref.name(), args, ref.nullable());
        if (t.base() == Base.UNKNOWN) {
            if (model.structs.containsKey(ref.name())) t = new Type(Base.STRUCT, ref.name(), args, ref.nullable());
            else if (model.traits.containsKey(ref.name())) t = new Type(Base.TRAIT, ref.name(), args, ref.nullable());
            else if (model.enums.containsKey(ref.name())) t = new Type(Base.ENUM, ref.name(), args, ref.nullable());
        }
        return t;
    }

    /** A resolved static reference (enum variant, static field, or primitive constant) as structured Java IR. */
    private JavaIr staticRefIr(String name, Type type) {
        if (type.base() == Base.ENUM && model.enums.containsKey(type.name())) return JavaIr.staticField(enumNames.get(type.name()), name, type);
        if (type.base() == Base.STRUCT && model.structs.containsKey(type.name())) return JavaIr.staticField(structNames.get(type.name()), fieldName(name), type);
        if (name.equals("MAX_VALUE") || name.equals("MIN_VALUE")) {
            return switch (type.base()) {
                case BYTE -> JavaIr.staticField("Byte", name, type);
                case SHORT -> JavaIr.staticField("Short", name, type);
                case INTEGER -> JavaIr.staticField("Integer", name, type);
                case LONG -> JavaIr.staticField("Long", name, type);
                // Solvik's Float/Double MIN_VALUE is the negative of MAX_VALUE.
                case FLOAT -> name.equals("MAX_VALUE") ? JavaIr.staticField("Float", name, type) : JavaIr.prefix("-", JavaIr.staticField("Float", "MAX_VALUE", type), type);
                case DOUBLE -> name.equals("MAX_VALUE") ? JavaIr.staticField("Double", name, type) : JavaIr.prefix("-", JavaIr.staticField("Double", "MAX_VALUE", type), type);
                default -> JavaIr.atom("0", type);
            };
        }
        if (type.base() == Base.FLOAT || type.base() == Base.DOUBLE) {
            String owner = type.base() == Base.FLOAT ? "Float" : "Double";
            return switch (name) {
                case "NaN", "POSITIVE_INFINITY", "NEGATIVE_INFINITY" -> JavaIr.staticField(owner, name, type);
                default -> JavaIr.staticField(generatedTypeName(type), name, type);
            };
        }
        return JavaIr.staticField(generatedTypeName(type), name, type);
    }
