    private String javaBuiltin(SolvikIr.Call c) {
        String builtin = c.builtin(); String args = argumentsOf(c);
        if (builtin.startsWith("enum:")) {
            String variant = builtin.substring(5); String typeArgs = c.receiverType() == null || c.receiverType().args().isEmpty() ? "" : "<" + c.receiverType().args().stream().map(x -> javaType(x, true)).reduce((a,b)->a+", "+b).orElse("") + ">";
            return generatedTypeName(c.receiverType()) + "." + typeArgs + variant + "(" + args + ")";
        }
        if (builtin.startsWith("object:")) {
            String receiver = checkedReceiverIr(c.receiver()); String method = builtin.substring(7);
            return switch (method) { case "toString" -> "RT.format(" + receiver + ")"; case "hashCode" -> "(long)RT.hash(" + receiver + ")"; default -> "RT.eq(" + receiver + ", " + args + ")"; };
        }
        if (builtin.startsWith("dynamic:")) {
            String name = builtin.substring(8);
            return "RT.dynamic(" + checkedReceiverIr(c.receiver()) + ", \"" + name + "\"" + (c.arguments().isEmpty() ? "" : ", " + args) + ")";
        }
        int dot = builtin.indexOf('.'); String namespace = dot < 0 ? builtin : builtin.substring(0, dot); String method = dot < 0 ? builtin : builtin.substring(dot + 1);
        Type receiverType = c.receiverType();
        if (c.receiver() != null) {
            String receiver = checkedReceiverIr(c.receiver());
            if (namespace.equals("String")) return switch (method) {
                case "length" -> "(long) (" + receiver + ".codePointCount(0, " + receiver + ".length()))";
                case "substring" -> "RT.strSubstring(" + receiver + ", " + args + ")";
                case "charAt" -> "RT.strCharAt(" + receiver + ", " + args + ")";
                case "indexOf" -> "(long)" + receiver + ".indexOf(" + args + ")";
                case "split" -> "RT.list((Object[])" + receiver + ".split(java.util.regex.Pattern.quote(" + args + ")) )";
                default -> receiver + "." + javaStringMethod(method) + "(" + args + ")";
            };
            if (namespace.equals("Process")) return switch (method) {
                case "wait" -> receiver + ".waitFor()";
                case "start" -> receiver + ".start()";
                case "stdout" -> receiver + ".stdout()";
                case "stderr" -> receiver + ".stderr()";
                case "stdin" -> receiver + ".stdin()";
                case "exitCode" -> receiver + ".exitCode()";
                default -> receiver + "." + methodName(method) + "(" + args + ")";
            };
            return receiver + "." + method + "(" + args + ")";
        }
        if (namespace.equals("System")) return switch (method) {
            case "getOut" -> "RT.out()"; case "getErr" -> "RT.err()"; case "getIn" -> "RT.in()";
            case "getLineSeparator" -> "System.lineSeparator()"; case "getCurrentTimeMillis" -> "System.currentTimeMillis()"; case "getNanoTime" -> "System.nanoTime()";
            case "getEnv" -> c.arguments().isEmpty() ? "RT.getenv()" : "System.getenv(" + args + ")";
            case "getProperty" -> "RT.property(" + args + ")"; case "setProperty" -> "RT.setProperty(" + args + ")"; case "clearProperty" -> "RT.clearProperty(" + args + ")";
            default -> "null";
        };
        if (namespace.equals("Math")) { if (method.equals("abs") && !c.arguments().isEmpty()) { Type argument = c.arguments().get(0).type(); if (argument.base() == Base.LONG) return "RT.absLong(" + args + ")"; if (argument.integral()) return "RT.absInt(" + args + ")"; } return "Math." + method + "(" + args + ")"; }
        if (namespace.equals("Base64")) return method.equals("encode") ? "Base64.getEncoder().encodeToString(" + args + ".getBytes(StandardCharsets.UTF_8))" : "new String(Base64.getDecoder().decode(" + args + "), StandardCharsets.UTF_8)";
        if (namespace.equals("Hash")) return "RT.digest(\"" + method.toUpperCase() + "\", " + args + ")";
        if (namespace.equals("Json")) return method.equals("stringify") ? "RT.json(" + args + ")" : "RT.parseJson(" + args + ")";
        if (namespace.equals("Time")) return method.equals("sleep") ? "RT.sleep(" + args + ")" : "System.currentTimeMillis()";
        if (namespace.equals("Random")) return method.equals("seed") ? "RT.seedRandom(" + args + ")" : method.equals("nextDouble") ? "RT.randomDouble()" : "RT.randomLong(" + args + ")";
        if (namespace.equals("Type")) return method.equals("of") ? "RT.typeOf(" + args + ")" : "RT.isType(" + args + ")";
        if (namespace.equals("File")) return switch (method) { case "read" -> "RT.fileRead("+args+")"; case "write" -> "RT.fileWrite("+args+")"; case "exists" -> "RT.fileExists("+args+")"; case "delete" -> "RT.fileDelete("+args+")"; case "listDir" -> "RT.fileList("+args+")"; default -> "null"; };
        if (namespace.equals("Test")) return method.equals("assert") ? "RT.assertValue(" + args + ")" : "RT.assertEqual(" + args + ")";
        if (namespace.equals("Regex")) return "new RT.Regex(" + args + ")";
        if (namespace.equals("Exception")) return "new RT.ExceptionValue(" + args + ")";
        if (namespace.equals("Thread")) return "new RT.ThreadValue(" + args + ")";
        if (namespace.equals("Mutex")) return "new RT.MutexValue()";
        if (namespace.equals("Semaphore")) return "new RT.SemaphoreValue(" + args + ")";
        if (namespace.equals("Process")) return "new RT.ProcessValue(" + args + ")";
        if (COLLECTION_NAMESPACES.contains(namespace)) return collectionConstructor(namespace, receiverType, c);
        if (CONVERSION_NAMESPACES.contains(namespace) && method.equals("from")) return conversion(namespace, c);
        return "null";
    }

    private String argumentsOf(SolvikIr.Call call) { StringBuilder b = new StringBuilder(); for (SolvikIr argument : call.arguments()) appendArg(b, emitIr(argument)); return b.toString(); }
    private String javaCall(SolvikIr.Call call) {
        if (call.staticOwnerType() != null && call.name().equals("new")) {
            int[] fieldToParameter = trivialFactories.get(call.staticOwnerType().name());
            if (fieldToParameter != null) return javaStaticConstructor(call, fieldToParameter);
        }
        String target;
        if (call.staticOwnerType() != null) { String typeArguments = call.staticTypeArguments() ? "<" + call.receiverType().args().stream().map(x -> javaType(x, true)).reduce((a,b)->a+", "+b).orElse("") + ">" : ""; target = generatedTypeName(call.staticOwnerType()) + "." + typeArguments + methodName(call.name()); }
        else if (call.receiver() != null) target = checkedReceiverIr(call.receiver()) + "." + methodName(call.name());
        else target = (call.implicitInstance() ? "this." : structNames.get(call.implicitOwner()) + ".") + methodName(call.name());
        return target + "(" + argumentsOf(call) + ")";
    }

    private Type builtinArgumentType(Type receiver, String method, int index) {
        if (receiver == null) return null;
        if (receiver.base() == Base.LIST) return (method.equals("addAt") && index == 0) || (method.equals("set") && index == 0) || method.equals("get") || method.equals("remove") ? named(Base.INTEGER,"Integer") : receiver.args().isEmpty()?null:receiver.args().get(0);
        if (receiver.base() == Base.MAP) { boolean valueFirst = method.equals("containsValue"); if (index == 0) return valueFirst ? (receiver.args().size()>1?receiver.args().get(1):null) : (receiver.args().isEmpty()?null:receiver.args().get(0)); return receiver.args().size()>1?receiver.args().get(1):null; }
        if (receiver.base() == Base.SET || receiver.base() == Base.STACK) return receiver.args().isEmpty()?null:receiver.args().get(0);
        if (receiver.base() == Base.STRING && (method.equals("substring") || method.equals("charAt"))) return named(Base.LONG,"Long");
        return null;
    }
    private String collectionConstructor(String namespace, Type receiverType, SolvikIr.Call call) {
        String java = switch (namespace) { case "List" -> "RT.SList"; case "Map" -> "RT.SMap"; case "Stack" -> "RT.SStack"; default -> "RT.SSet"; };
        // A capacity argument pre-sizes the backing collection and is evaluated
        // once; the no-argument form keeps the default constructor.
        if (call.arguments().size() == 1) return "new " + java + "<>" + "(" + emitIr(call.arguments().get(0)) + ")";
        return "new " + java + "<>()";
    }
    private String conversion(String namespace, SolvikIr.Call call) {
        if (call.arguments().size() == 1) {
            SolvikIr value = call.arguments().get(0);
            Type source = value.type();
            if (source != null && !source.nullable()) {
                // Constant/integral sources build their target directly: no String round trip.
                if (namespace.equals("BigInteger") && source.integral()) {
                    if (value instanceof SolvikIr.Literal l && l.kind() == LiteralKind.INT) {
                        try {
                            return "BigInteger.valueOf(" + new BigInteger(SemanticAnalyzer.cleanInteger(l.text())).longValueExact() + "L)";
                        } catch (RuntimeException e) { /* fall through to the general path */ }
                    }
                    return "BigInteger.valueOf(" + emitIr(value) + ")";
                }
                String rendered = emitIr(value);
                Base target = switch (namespace) {
                    case "Double" -> Base.DOUBLE;
                    case "Float" -> Base.FLOAT;
                    case "Long" -> Base.LONG;
                    case "Integer" -> Base.INTEGER;
                    case "Short" -> Base.SHORT;
                    case "Byte" -> Base.BYTE;
                    case "Boolean" -> Base.BOOLEAN;
                    case "String" -> Base.STRING;
                    case "BigInteger" -> Base.BIG_INTEGER;
                    case "BigDecimal" -> Base.BIG_DECIMAL;
                    default -> null;
                };
                if (target != null && conversionAccepts(source, target)) {
                    // A same-type conversion is already the correct Java value; only a real
                    // numeric conversion needs an explicit cast. The cast also fixes the
                    // compile-time type so boxing yields the requested wrapper class.
                    return source.base() == target ? rendered : "(" + primitiveCast(target) + ")(" + rendered + ")";
                }
            }
        }
        String args = argumentsOf(call);
        return switch (namespace) {
            case "Long" -> "RT.convertLong(" + args + ")";
            case "Integer" -> "RT.convertInt(" + args + ")";
            case "Short" -> "RT.convertShort(" + args + ")";
            case "Byte" -> "RT.convertByte(" + args + ")";
            case "Double" -> "RT.convertDouble(" + args + ")";
            case "Float" -> "RT.convertFloat(" + args + ")";
            case "Boolean" -> "RT.convertBoolean(" + args + ")";
            case "Char" -> "RT.convertChar(" + args + ")";
            case "BigInteger" -> "RT.convertBigInteger(" + args + ")";
            case "BigDecimal" -> "RT.convertBigDecimal(" + args + ")";
            default -> "RT.convertString(" + args + ")";
        };
    }

    private boolean conversionAccepts(Type source, Base target) {
        Base s = source.base();
        return switch (target) {
            case DOUBLE, FLOAT -> source.floating() || source.integral();
            case LONG -> source.integral();
            case INTEGER -> s == Base.BYTE || s == Base.SHORT || s == Base.INTEGER;
            case SHORT -> s == Base.BYTE || s == Base.SHORT;
            case BYTE -> s == Base.BYTE;
            case BOOLEAN -> s == Base.BOOLEAN;
            case STRING -> s == Base.STRING;
            case BIG_INTEGER -> s == Base.BIG_INTEGER;
            case BIG_DECIMAL -> s == Base.BIG_DECIMAL;
            default -> false;
        };
    }
    private String primitiveCast(Base target) {
        return switch (target) {
            case DOUBLE -> "double";
            case FLOAT -> "float";
            case LONG -> "long";
            case INTEGER -> "int";
            case SHORT -> "short";
            case BYTE -> "byte";
            default -> "";
        };
    }
    private String javaStringMethod(String method) { return switch (method) { case "startsWith" -> "startsWith"; case "endsWith" -> "endsWith"; case "contains" -> "contains"; case "replace" -> "replace"; case "trim" -> "trim"; case "toUpperCase" -> "toUpperCase"; case "toLowerCase" -> "toLowerCase"; default -> method; }; }
